export async function GET() {
  const zip = new yazl.ZipFile();
  for (const [name, source] of Object.entries(files)) zip.addBuffer(Buffer.from(source), `forge-supabase-starter/${name}`);
  zip.end();
  const chunks: Buffer[] = [];
  for await (const chunk of zip.outputStream) chunks.push(Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk));
  return new Response(new Uint8Array(Buffer.concat(chunks)), {
    headers: {
      "Content-Type": "application/zip",
      "Content-Disposition": 'attachment; filename="forge-supabase-starter.zip"',
      "Cache-Control": "no-store",
    },
  });
}
